import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

// Embed the installed library bytes for the Worker, without filesystem access at runtime.
const assets = [];
for (const [name, contentType] of [
  ["footer.css", "text/css; charset=utf-8"],
  ["footer.js", "text/javascript; charset=utf-8"],
]) {
  const bytes = await readFile(new URL(`../node_modules/@saas-maker/ui/${name}`, import.meta.url));
  assets.push([`/${name}`, {
    base64: bytes.toString("base64"),
    contentType,
    cacheControl: "public, max-age=300",
    sha256: createHash("sha256").update(bytes).digest("hex"),
  }]);
}
await writeFile(new URL("../src/footer-library.ts", import.meta.url),
  `// Generated by scripts/sync-footer-assets.mjs from the installed @saas-maker/ui package.\nexport const FOOTER_LIBRARY_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`);
